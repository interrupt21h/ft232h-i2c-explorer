package io.github.interrupt21h.i2cexplorer

/** GC9A01 write-only SPI display. A successful USB transfer is not proof of a working panel. */
object Gc9a01 {
    const val WIDTH = 240
    const val HEIGHT = 240
    enum class Pattern { RED, GREEN, BLUE, WHITE, BLACK, BARS, CHECKERBOARD, GRADIENT, CIRCLES }
    private fun cmd(bus: Ft232h, value: Int, vararg data: Int) {
        bus.spiWrite(true, byteArrayOf(value.toByte()))
        if (data.isNotEmpty()) bus.spiWrite(false, ByteArray(data.size) { data[it].toByte() })
    }
    fun initialize(bus: Ft232h) {
        bus.spiReset()
        cmd(bus, 0xEF)
        cmd(bus, 0xEB, 0x14)
        cmd(bus, 0xFE)
        cmd(bus, 0xEF)
        cmd(bus, 0xEB, 0x14)
        cmd(bus, 0x84, 0x40)
        cmd(bus, 0x85, 0xFF)
        cmd(bus, 0x86, 0xFF)
        cmd(bus, 0x87, 0xFF)
        cmd(bus, 0x88, 0x0A)
        cmd(bus, 0x89, 0x21)
        cmd(bus, 0x8A, 0x00)
        cmd(bus, 0x8B, 0x80)
        cmd(bus, 0x8C, 0x01)
        cmd(bus, 0x8D, 0x01)
        cmd(bus, 0x8E, 0xFF)
        cmd(bus, 0x8F, 0xFF)
        cmd(bus, 0xB6, 0x00, 0x20)
        cmd(bus, 0x36, 0x08)
        cmd(bus, 0x3A, 0x05)
        cmd(bus, 0x90, 0x08, 0x08, 0x08, 0x08)
        cmd(bus, 0xBD, 0x06)
        cmd(bus, 0xBC, 0x00)
        cmd(bus, 0xFF, 0x60, 0x01, 0x04)
        cmd(bus, 0xC3, 0x13)
        cmd(bus, 0xC4, 0x13)
        cmd(bus, 0xC9, 0x22)
        cmd(bus, 0xBE, 0x11)
        cmd(bus, 0xE1, 0x10, 0x0E)
        cmd(bus, 0xDF, 0x21, 0x0C, 0x02)
        cmd(bus, 0xF0, 0x45, 0x09, 0x08, 0x08, 0x26, 0x2A)
        cmd(bus, 0xF1, 0x43, 0x70, 0x72, 0x36, 0x37, 0x6F)
        cmd(bus, 0xF2, 0x45, 0x09, 0x08, 0x08, 0x26, 0x2A)
        cmd(bus, 0xF3, 0x43, 0x70, 0x72, 0x36, 0x37, 0x6F)
        cmd(bus, 0xED, 0x1B, 0x0B)
        cmd(bus, 0xAE, 0x77)
        cmd(bus, 0xCD, 0x63)
        cmd(bus, 0x70, 0x07, 0x07, 0x04, 0x0E, 0x0F, 0x09, 0x07, 0x08, 0x03)
        cmd(bus, 0xE8, 0x34)
        cmd(bus, 0x62, 0x18, 0x0D, 0x71, 0xED, 0x70, 0x70, 0x18, 0x0F, 0x71, 0xEF, 0x70, 0x70)
        cmd(bus, 0x63, 0x18, 0x11, 0x71, 0xF1, 0x70, 0x70, 0x18, 0x13, 0x71, 0xF3, 0x70, 0x70)
        cmd(bus, 0x64, 0x28, 0x29, 0xF1, 0x01, 0xF1, 0x00, 0x07)
        cmd(bus, 0x66, 0x3C, 0x00, 0xCD, 0x67, 0x45, 0x45, 0x10, 0x00, 0x00, 0x00)
        cmd(bus, 0x67, 0x00, 0x3C, 0x00, 0x00, 0x00, 0x01, 0x54, 0x10, 0x32, 0x98)
        cmd(bus, 0x74, 0x10, 0x85, 0x80, 0x00, 0x00, 0x4E, 0x00)
        cmd(bus, 0x98, 0x3E, 0x07)
        cmd(bus, 0x35, 0x00)
        cmd(bus, 0x21)
        cmd(bus, 0x11)
        Thread.sleep(120)
        cmd(bus, 0x29)
        Thread.sleep(20)
    }
    fun pixel(pattern: Pattern, x: Int, y: Int): Int = when (pattern) {
        Pattern.RED -> 0xF800
        Pattern.GREEN -> 0x07E0
        Pattern.BLUE -> 0x001F
        Pattern.WHITE -> 0xFFFF
        Pattern.BLACK -> 0
        Pattern.BARS -> intArrayOf(0xF800, 0x07E0, 0x001F, 0xFFFF, 0x0000, 0xFFE0)[x / 40]
        Pattern.CHECKERBOARD -> if (((x / 12) + (y / 12)) % 2 == 0) 0xFFFF else 0
        Pattern.GRADIENT -> (((x * 31 / 239) shl 11) or ((y * 63 / 239) shl 5) or ((x * 31 / 239)))
        Pattern.CIRCLES -> {
            val d = (x - 120) * (x - 120) + (y - 120) * (y - 120)
            if (d > 119 * 119) 0 else if ((kotlin.math.sqrt(d.toDouble()).toInt() / 12) % 2 == 0) 0xFFFF else 0x001F
        }
    }
    fun draw(bus: Ft232h, pattern: Pattern) {
        cmd(bus, 0x2A, 0, 0, 0, 239)
        cmd(bus, 0x2B, 0, 0, 0, 239)
        cmd(bus, 0x2C)
        // 240 RGB565 pixels per row. Stream each row without allocating a full framebuffer.
        for (y in 0 until HEIGHT) {
            val row = ByteArray(WIDTH * 2)
            for (x in 0 until WIDTH) {
                val c = pixel(pattern, x, y)
                row[x * 2] = (c shr 8).toByte()
                row[x * 2 + 1] = c.toByte()
            }
            bus.spiWrite(false, row)
        }
    }
}
